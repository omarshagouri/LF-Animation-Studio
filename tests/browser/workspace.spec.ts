import { expect, test } from '@playwright/test'

test('five modules share local workspace data without remote requests', async ({ page }, testInfo) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', req => {
    if (!req.url().startsWith('http://127.0.0.1:4173/') && /^https?:/.test(req.url())) external.push(req.url())
  })
  const button = (name: string | RegExp) => page.getByRole('button', { name })
  const choice = (name: string) => page.getByRole('radio', { name, exact: true })
  const field = (label: string) => page.getByRole('textbox', { name: label, exact: true })
  const back = () => page.getByRole('link', { name: /, back$/ }).click()

  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Omar Studio' })).toBeVisible()
  const framed = await page.locator('div').evaluateAll(nodes =>
    nodes.some(node => node.getBoundingClientRect().width === 390 && getComputedStyle(node).borderTopWidth === '8px'))
  expect(framed).toBe(testInfo.project.name === 'desktop')

  await button(/AI Meeting Assistant/).click()
  await field('Meeting title (optional)').fill('Synthetic meeting')
  await button('Start recording').click()
  await expect(page.getByText(/00:00:0[1-9]/)).toBeVisible()
  await button('Stop recording').click()
  await button(/Synthetic meeting/).click()
  await expect(button(/Upload audio|Generate AI notes/)).toHaveCount(0)
  await field('Transcript or meeting notes').fill('Synthetic notes for the browser test.')
  await back()
  await button(/Synthetic meeting/).click()
  await expect(field('Transcript or meeting notes')).toHaveValue('Synthetic notes for the browser test.')
  await back()
  await back()

  await button(/Universal Capture/).click()
  await field('Content').fill('Synthetic deadline follow up')
  await expect(choice('Category: task')).toHaveAttribute('aria-checked', 'true')
  await button('Save to inbox').click()
  await button('Create follow-up task').click()
  await button('Create follow-up task').click()
  await back()

  await button(/Personal Secretary/).click()
  await expect(page.getByText('Open · 1', { exact: true })).toBeVisible()
  await button('Complete').click()
  await expect(page.getByText('Completed · 1')).toBeVisible()
  await button('Reopen').click()
  await expect(page.getByText('Open · 1')).toBeVisible()
  await field('New task').fill('Synthetic date validation')
  await field('Due date (YYYY-MM-DD, optional)').fill('2026-02-30')
  await button('Add task').click()
  await expect(page.getByText(/optional valid YYYY-MM-DD/)).toBeVisible()
  await back()

  await button(/Padel Intelligence/).click()
  await field('Partner').fill('Synthetic partner')
  await field('Opponents').fill('Synthetic opponents')
  await choice('Playing side: right').click()
  await field('Our score').fill('6')
  await field('Their score').fill('4')
  await button('Save match').click()
  await expect(page.getByText('100%', { exact: true })).toBeVisible()
  await expect(page.getByText(/Right: 1\/1/)).toBeVisible()
  await button('Remove result').click()
  await expect(page.getByText('Observed win rate · 0 matches')).toBeVisible()
  await back()

  await button(/AmpCoreX Control Center/).click()
  await field('Title or video ID').fill('Synthetic video')
  await choice('Format: SF').click()
  await choice('Stage: Scripted').click()
  await field('Next action').fill('Review synthetic storyboard')
  await button('Add item').click()
  await choice('Local stage: Recorded').click()
  await expect(page.getByText('SF · Recorded')).toBeVisible()
  await button('Add action to Secretary').click()
  await back()
  await button(/Personal Secretary/).click()
  await expect(page.getByText('Review synthetic storyboard')).toBeVisible()
  await back()

  await button(/Settings/).click()
  await expect(page.getByText(/System appearance · (Dark|Light)/)).toBeVisible()
  await expect(field('Access token')).toHaveCount(0)
  await page.reload()
  await expect(page.getByText('0 open actions · 0 saved meetings')).toBeVisible()
  expect(external).toEqual([])
  expect(errors).toEqual([])
})
